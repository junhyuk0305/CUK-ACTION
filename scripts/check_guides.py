"""Browser acceptance checks. Only local test accounts and isolated browser data."""
import sys
from playwright.sync_api import sync_playwright, expect

url=sys.argv[1] if len(sys.argv)>1 else 'http://127.0.0.1:5198'
with sync_playwright() as p:
    browser=p.chromium.launch(channel='msedge',headless=True)
    ctx=browser.new_context(viewport={'width':1380,'height':900})
    page=ctx.new_page()
    errors=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('dialog',lambda d:d.accept())
    page.goto(url); page.wait_for_load_state('networkidle')
    search=page.get_by_role('searchbox',name='공고 검색')
    search.fill('동계 직무 부트캠프')
    page.locator('#open-277842').click()
    guide=page.get_by_role('region',name='학생 안내')
    expect(guide).to_contain_text('2026.12.14.')
    guide.get_by_text('모집 마감 원문 근거').click()
    expect(guide.locator('details[open]')).to_contain_text('모집일정')
    guide.get_by_role('button',name='건너뛰기').click()
    expect(guide).to_contain_text('대상은 재학생 전체입니다.')
    page.get_by_role('button',name='관심 공고에 저장',exact=True).click()
    page.get_by_role('button',name='홈으로').click()
    expect(search).to_have_value('동계 직무 부트캠프')
    page.get_by_role('link',name='관심 공고',exact=True).click()
    page.locator('#open-277842').click()
    guide.get_by_label('재학 여부').select_option('재학')
    page.reload()
    expect(guide).to_contain_text('재학생 대상 조건을 충족합니다.')
    expect(guide.get_by_label('재학 여부')).to_have_count(0)
    page.get_by_role('link',name='전체 공고',exact=True).click()
    search.fill('277389');page.locator('#open-277389').click()
    expect(guide).to_contain_text('09:00 ~ 16:00')
    expect(guide).to_contain_text('09:00 ~ 17:00')
    expect(guide).to_contain_text('변경이 필요한 경우')
    print('PASS public search, evidence, bookmark, profile and exchange schedules')
    page.get_by_role('link',name='로그인',exact=True).click()
    button=lambda name:page.get_by_role('button',name=name,exact=True)
    button('담당자 A로 체험').click()
    page.locator('.sidebar').get_by_role('button',name='공고 관리').click()
    button('테스트 초안 불러오기').click()
    result=page.get_by_label('검수 결과')
    expect(result).to_have_count(3)
    result.nth(0).select_option('accept')
    page.get_by_label('최종값').nth(1).fill('2026.12.14')
    button('학생 안내 승인').click()
    expect(page.get_by_text('승인한 항목을 학생 안내에 반영했습니다.')).to_be_visible()
    page.get_by_label('최종값').nth(1).fill('2030.12.14')
    button('학생 안내 승인').click()
    expect(page.get_by_text('채택할 값과 원문 근거를 다시 확인하세요.')).to_be_visible()
    button('AI 초안 만들기').click()
    expect(page.get_by_text('테스트 공간에서는 모델 키를',exact=False)).to_be_visible()
    expect(page.get_by_label('최종값').nth(1)).to_have_value('2030.12.14')
    page.locator('.manager-notice').filter(has_text='학생 프로젝트 모집').get_by_text('집계 보기').click()
    expect(page.get_by_text('가상 응답',exact=True)).to_be_visible()
    expect(page.get_by_text('1위 대상 5명')).to_be_visible()
    expect(page.get_by_text('1위 준비물 5명')).to_be_visible()
    page.get_by_label('집계 시작일',exact=True).fill(page.get_by_label('집계 종료일',exact=True).input_value())
    button('집계 조회').click()
    expect(page.get_by_text('이 기간에는 연결된 학생 응답 자료가 없습니다.')).to_be_visible()
    button('로그아웃').click()
    button('학생 A로 체험').click()
    button('실제 공고 보관함').click()
    page.get_by_label('실제 공고 검색').fill('277842')
    page.locator('.archive-list button').first.click()
    expect(guide).to_contain_text('2026.12.14')
    expect(guide.get_by_text('운영기간',exact=True)).to_have_count(0)
    expect(guide).not_to_contain_text('2030')
    # Public catalogue never reads test approvals.
    page.goto(url+'/#notice/277842')
    expect(guide.get_by_text('운영기간',exact=True)).to_be_visible()
    assert not errors,errors
    print('PASS manager review, failed extraction/approval, student publication, test isolation, response report and empty period')
    browser.close()
